def circumsphere(p1, p2, p3, p4):
    """Gets the center and radius of the corresponding tetrahedra.
    This solves the equation : 2*(p_i-p_1)x_i = (||p_i||^2-||p_1||^2)/2 for i in [2,3,4]"""
    A = np.array([p2 - p1, p3 - p1, p4 - p1]).T
    b  = np.array([
        np.dot(p2, p2) - np.dot(p1, p1),
        np.dot(p3, p3) - np.dot(p1, p1),
        np.dot(p4, p4) - np.dot(p1, p1),
    ]) / 2.0

    center = np.linalg.solve(A, b) + p1 #since we are solving for C'=C-p1
    radius = np.linalg.norm(center - p1)
    return center, radius

def alpha_shape_surface(points: np.ndarray, alpha: float) -> np.ndarray:
    tri = Delaunay(points)
    simplices = tri.simplices       
    neighbors = tri.neighbors         
 
    radii = np.array([
        circumsphere(points[s[0]], points[s[1]], points[s[2]], points[s[3]])[1]
        for s in simplices
    ])
 
    kept = radii <= alpha
    print(f" {kept.sum()} / {len(simplices)} tetrahedra kept for alpha = {alpha}.")
    triangles = []
    face_indices = [(1, 2, 3), (0, 2, 3), (0, 1, 3), (0, 1, 2)]
 
    for i, simplex in enumerate(simplices):
        if not kept[i]:
            continue
        for j, face in enumerate(face_indices):
            neighbor_idx = neighbors[i, j]
            # boundary face: neighbor not kept, or outside convex hull
            if neighbor_idx == -1 or not kept[neighbor_idx]:
                tri_verts = points[list(simplex[k] for k in face)]
                triangles.append(tri_verts)
 
    return np.array(triangles) if triangles else np.empty((0, 3, 3))

# Q1. Automatically finding the best alpha
def auto_alpha(points: np.ndarray, percentile: float = 10.0) -> float:
    tri = Delaunay(points)
    radii = np.array([
        circumsphere(points[s[0]], points[s[1]], points[s[2]], points[s[3]])[1]
        for s in tri.simplices
    ])
    finite_radii = radii[np.isfinite(radii)]
    alpha = float(np.percentile(finite_radii, percentile))
    return alpha

def local_density_alpha(points: np.ndarray, k: int = 10, scale: float = 2.0) -> np.ndarray:
    from scipy.spatial import cKDTree
 
    tree = cKDTree(points)
    # query k+1 because the point itself is the first result
    dists, _ = tree.query(points, k=k + 1)
    mean_knn_dist = dists[:, 1:].mean(axis=1)   # exclude self-distance
    per_point_alpha = scale * mean_knn_dist
    return per_point_alpha
 
