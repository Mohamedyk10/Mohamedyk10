from scipy.spatial.distance import pdist

def adaptive_alpha_shape_surface(points: np.ndarray, k: int = 15, scale: float = 3.5) -> np.ndarray:
    """
    Adaptive alpha shape using Maximum Edge Length instead of Circumsphere Radius.
    """
    # 1. Calculate base density (k=15 provides a smoother neighborhood)
    # Scale of 3.0 to 4.0 is usually the sweet spot for edge-length filtering
    per_point_alpha = local_density_alpha(points, k=k, scale=scale)
    
    tri = Delaunay(points)
    simplices = tri.simplices
    neighbors = tri.neighbors
    
    kept = np.zeros(len(simplices), dtype=bool)
    
    for i, s in enumerate(simplices):
        # Get the 3D coordinates of the 4 vertices of the tetrahedron
        tetra_pts = points[s]
        
        # Calculate the 6 edge lengths of the tetrahedron and find the longest one
        max_edge = pdist(tetra_pts).max()
        
        # Use max() of the 4 vertices' local densities to prevent tearing
        local_alpha = per_point_alpha[s].max()
        
        # Keep if the longest edge is smaller than the local threshold
        kept[i] = max_edge <= local_alpha
        
    print(f"Adaptive filter (Edge Method): {kept.sum()} / {len(simplices)} tetrahedra kept.")
    
    # --- Face Extraction (Unchanged) ---
    triangles = []
    for i, simplex in enumerate(simplices):
        if not kept[i]:
            continue
        for j, face in enumerate(FACE_INDICES):
            neighbor_idx = neighbors[i, j]
            if neighbor_idx == -1 or not kept[neighbor_idx]:
                v0, v1, v2 = points[simplex[list(face)]]
                opposite_vert = points[simplex[j]]
                
                n = np.cross(v1 - v0, v2 - v0)
                if np.dot(n, v0 - opposite_vert) < 0:
                    triangles.append(np.array([v0, v2, v1]))
                else:
                    triangles.append(np.array([v0, v1, v2]))
                    
    return np.array(triangles) if triangles else np.empty((0, 3, 3))

FACE_INDICES = [(1,2,3), (0,2,3), (0,1,3), (0,1,2)]

def triangle_normal(v0, v1, v2):
    """Normal of a triangle, used for stl writing."""
    n = np.cross(v1 - v0, v2 - v0)
    norm = np.linalg.norm(n)
    if norm == 0:
        return np.zeros(3)
    return n / norm

def write_stl(triangles, path, name="mesh"):
    with open(path, "w") as f:
        f.write(f"solid {name}\n")
        for triangle in triangles:
            v0, v1, v2 = triangle[0], triangle[1], triangle[2]
            n = triangle_normal(v0, v1, v2)
            f.write(f"  facet normal {n[0]:.6e} {n[1]:.6e} {n[2]:.6e}\n")
            f.write( "    outer loop\n")
            f.write(f"      vertex {v0[0]:.6e} {v0[1]:.6e} {v0[2]:.6e}\n")
            f.write(f"      vertex {v1[0]:.6e} {v1[1]:.6e} {v1[2]:.6e}\n")
            f.write(f"      vertex {v2[0]:.6e} {v2[1]:.6e} {v2[2]:.6e}\n")
            f.write( "    endloop\n")
            f.write( "  endfacet\n")
        f.write(f"endsolid {name}\n")
    print(f"STL written → {path}")

