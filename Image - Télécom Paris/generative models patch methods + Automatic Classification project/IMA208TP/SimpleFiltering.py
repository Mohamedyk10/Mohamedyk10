def circumsphere(tetra):
    """Gets the center and radius of the corresponding tetrahedra.
    This solves the equation : 2*(p_i-p_1)x_i = (||p_i||^2-||p_1||^2)/2 for i in [2,3,4]"""
    p1, p2, p3, p4 = tetra
    A = np.array([p2 - p1, p3 - p1, p4 - p1]).T
    b  = np.array([
        np.dot(p2, p2) - np.dot(p1, p1),
        np.dot(p3, p3) - np.dot(p1, p1),
        np.dot(p4, p4) - np.dot(p1, p1),
    ]) / 2.0

    center = np.linalg.solve(A, b) + p1 #since we are solving for C'=C-p1
    radius = np.linalg.norm(center - p1)
    return center, radius

