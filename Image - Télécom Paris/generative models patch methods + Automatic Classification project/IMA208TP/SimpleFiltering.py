def compute_local_scale(points, k=10):
    """
    For each point, estimate the mean distance to its k nearest neighbors.

    Returns : an array of shape (N,)
    """
    dist_matrix = distance.cdist(points, points)
    partitioned = np.partition(dist_matrix, k + 1, axis=1)
    mean_nn_dist = partitioned[:, 1:k + 1].mean(axis=1)

    return mean_nn_dist

def adaptive_alpha_filter(simplices, points, local_scale, scale_factor=3.0):
    """
    For each tetrahedron, its threshold = scale_factor × (mean local scale
    of its 4 vertices). 
    """
    kept = []
    for tet, r in zip(simplices, all_radiusses):
        if not np.isfinite(r):
            continue
        local_alpha = scale_factor * local_scale[tet].mean()
        if r <= local_alpha:
            kept.append(tet)
    return kept

