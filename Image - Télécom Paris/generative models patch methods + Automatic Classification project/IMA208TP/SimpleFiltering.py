# Q1. Automatically finding the alpha  -----------------------------------------------------------
all_radiusses = np.array([circumsphere(points3D[tet])[1] for tet in tri.simplices])
def find_auto_alpha(radii, jump_factor=5.0):
    """
      - Sort all radiuses.
      - Compute the ratio between each consecutive pair (r[i+1] / r[i]).
      - Select the first ratio where ratio>jump_factor.

    jump_factor: how many times larger the next radius must be to count.
    """
    finite = radii[np.isfinite(radii)]
    sorted_r = np.sort(finite)

    ratios = sorted_r[1:] / (sorted_r[:-1] + 1e-12)

    jump_indices = np.where(ratios > jump_factor)[0]

    if len(jump_indices) == 0:
        # No clear jump → fall back to 10th percentile
        alpha = np.percentile(sorted_r, 10)
        print(f"[Auto alpha] No jump found, using 10th percentile: {alpha:.5f}")
    else:
        # Cut at the value just BEFORE the first big jump
        cut = jump_indices[0]
        alpha = sorted_r[cut]
        print(f"Found alpha = {alpha:.5f}")

    return alpha

auto_alpha = find_auto_alpha(all_radiusses)
kept_global = [tet for tet, r in zip(tri.simplices, all_radiusses) if r <= auto_alpha]
print(f"[Global] Kept {len(kept_global)} / {len(tri.simplices)} tetrahedra\n")

