def triangle_normal(v0, v1, v2):
    """Normal of a triangle, used for stl writing."""
    n = np.cross(v1 - v0, v2 - v0)
    norm = np.linalg.norm(n)
    if norm == 0:
        return np.zeros(3)
    return n / norm

